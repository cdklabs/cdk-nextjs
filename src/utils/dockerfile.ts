/** First line of every Dockerfile in `src/nextjs-build`. */
export const GENERATED_DOCKERFILE_HEADER = "# ~~ Generated by cdk-nextjs ~~";

/**
 * Whether cdk-nextjs wrote this Dockerfile, and may therefore replace it. Reads
 * only the first line: the rest is free to have been edited, and an edit that
 * keeps the header is an edit that asked to be overwritten.
 */
export function isGeneratedDockerfileContent(text: string): boolean {
  return text.split("\n", 1)[0].startsWith(GENERATED_DOCKERFILE_HEADER);
}

/**
 * What to do with the Dockerfile in the build context:
 * - `keep`: the developer wrote it, so it is theirs and left alone.
 * - `unchanged`: it is already this version's generated one.
 * - `create`: there is none, so write `content`.
 * - `replace`: a generated one from another version, to be backed up and
 *   overwritten with `content`.
 */
export type DockerfileAction =
  | { readonly kind: "keep" }
  | { readonly kind: "unchanged" }
  | { readonly kind: "create"; readonly content: string }
  | { readonly kind: "replace"; readonly content: string };

/**
 * Decides the {@link DockerfileAction} for the build context's Dockerfile
 * (`existing`, `undefined` when there is none) given this version's generated
 * one.
 *
 * A Dockerfile the developer wrote is theirs; one cdk-nextjs generated is ours
 * to keep current, and the header says as much. Without that check, a
 * generated Dockerfile from an older version silently wins — and the ones this
 * version replaces run `node server.js`, which no longer exists now that the
 * build stages a deployment root instead of `.next/standalone`, so the
 * container crash-loops on MODULE_NOT_FOUND until someone deletes it.
 *
 * `generated` is only called once the existing Dockerfile is known not to be
 * the developer's, so a deployment that brings its own never needs the
 * package's copy.
 */
export function dockerfileAction(
  existing: string | undefined,
  generated: () => string,
): DockerfileAction {
  if (existing !== undefined && !isGeneratedDockerfileContent(existing)) {
    return { kind: "keep" };
  }
  const content = generated();
  if (existing === undefined) {
    return { kind: "create", content };
  }
  // Replaced all the same when it differs — a generated file from an older
  // version runs a server that no longer exists — but the caller keeps it
  // beside the new one, so an edit made under the header isn't lost without a
  // word.
  return existing === content
    ? { kind: "unchanged" }
    : { kind: "replace", content };
}
